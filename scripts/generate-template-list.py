import os
import re

def parse_frontmatter(content):
    frontmatter = {}
    if content.startswith('---'):
        end = content.find('---', 3)
        if end != -1:
            fm_text = content[3:end].strip()
            for line in fm_text.split('\n'):
                if ':' in line:
                    key, value = line.split(':', 1)
                    frontmatter[key.strip()] = value.strip().strip("'").strip('"')
    return frontmatter

def get_title(content, filename):
    # Try to find the first H1
    match = re.search(r'^#\s+(.*)', content, re.MULTILINE)
    if match:
        return match.group(1).strip()
    return filename

def generate_list():
    base_dir = "templates"
    output_file = "docs/template-list.md"
    
    sections = {
        "Agents": "agents",
        "Prompts": "prompts",
        "Instructions": "instructions"
    }
    
    with open(output_file, 'w', encoding='utf-8') as f:
        f.write("# Template List\n\n")
        f.write("This page lists all available Agents, Prompts, and Instructions in this repository. This file is automatically generated.\n\n")
        f.write("[Table of Contents](#table-of-contents)\n")
        f.write("- [Agents](#agents)\n")
        f.write("- [Prompts](#prompts)\n")
        f.write("- [Instructions](#instructions)\n")
        f.write("- [Global Instructions](#global-instructions)\n\n")
        
        for section_name, folder in sections.items():
            f.write(f"## {section_name}\n\n")
            f.write("| Name | Description | File |\n")
            f.write("| :--- | :--- | :--- |\n")
            
            folder_path = os.path.join(base_dir, folder)
            if not os.path.exists(folder_path):
                continue
                
            files = sorted(os.listdir(folder_path))
            for filename in files:
                if not filename.endswith(".md"):
                    continue
                
                path = os.path.join(folder_path, filename)
                with open(path, 'r', encoding='utf-8') as tf:
                    content = tf.read()
                    
                fm = parse_frontmatter(content)
                title = fm.get('name') or get_title(content, filename)
                description = fm.get('description', '-')
                
                # Relative link from docs/ to templates/
                github_link = f"../templates/{folder}/{filename}"
                
                f.write(f"| {title} | {description} | [{filename}]({github_link}) |\n")
            
            f.write("\n")
            
        # Add global instructions if exists
        global_instr = os.path.join(base_dir, "copilot-instructions.md")
        if os.path.exists(global_instr):
            f.write("## Global Instructions\n\n")
            f.write(f"- [copilot-instructions.md](../templates/copilot-instructions.md)\n")

    print(f"Successfully generated {output_file}")

if __name__ == "__main__":
    generate_list()
