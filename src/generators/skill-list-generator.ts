import * as fs from 'fs';
import * as path from 'path';
import { parseFrontmatter } from './template-list-generator';

export function generateSkillList(
  templatesBaseDir = 'templates',
  outputFile = 'docs/skill-list.md'
) {
  const outputDir = path.dirname(outputFile);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Collect domain directories
  const domains: string[] = [];
  if (fs.existsSync(templatesBaseDir)) {
    fs.readdirSync(templatesBaseDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort()
      .forEach((d) => domains.push(d));
  }

  interface SkillEntry {
    domain: string;
    name: string;
    description: string;
    filename: string;
  }

  const allSkills: SkillEntry[] = [];
  const byDomain: Record<string, SkillEntry[]> = {};

  for (const domain of domains) {
    const domainDir = path.join(templatesBaseDir, domain);
    const skillsSubdir = path.join(domainDir, 'skills');
    if (!fs.existsSync(skillsSubdir)) continue;

    const skillDirs = fs
      .readdirSync(skillsSubdir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();

    const validSkillDirs = skillDirs.filter((name) =>
      fs.existsSync(path.join(skillsSubdir, name, 'SKILL.md'))
    );
    if (validSkillDirs.length === 0) continue;

    byDomain[domain] = [];
    for (const skillName of validSkillDirs) {
      const skillMdPath = path.join(skillsSubdir, skillName, 'SKILL.md');
      const content = fs.readFileSync(skillMdPath, 'utf8');
      const fm = parseFrontmatter(content);
      const name = fm.name || skillName;
      const description = fm.description || '-';
      const filename = `skills/${skillName}/SKILL.md`;
      const entry: SkillEntry = { domain, name, description, filename };
      allSkills.push(entry);
      byDomain[domain].push(entry);
    }
  }

  let output = `# Skill List\n\n`;
  output += `This page lists all available skills organized by domain. This file is automatically generated.\n\n`;
  output += `> Skills become available as slash commands after installing the corresponding plugin via \`gh copilot plugin install\`.\n\n`;

  // Overview table
  output += `## Overview\n\n`;
  output += `| Skill | Domain | Description |\n`;
  output += `| :---- | :----- | :---------- |\n`;

  for (const s of allSkills) {
    const skillLink = `[${s.name}](../templates/${s.domain}/${s.filename})`;
    const domainLabel = s.domain.charAt(0).toUpperCase() + s.domain.slice(1);
    const domainLink = `[${domainLabel}](#${s.domain})`;
    output += `| ${skillLink} | ${domainLink} | ${s.description} |\n`;
  }
  output += `\n`;

  // Per-domain sections
  for (const [domain, skills] of Object.entries(byDomain)) {
    const label = domain.charAt(0).toUpperCase() + domain.slice(1);
    output += `## ${label}\n\n`;
    output += `| Skill | Description |\n`;
    output += `| :---- | :---------- |\n`;
    for (const s of skills) {
      const skillLink = `[\`${s.name}\`](../templates/${s.domain}/${s.filename})`;
      output += `| ${skillLink} | ${s.description} |\n`;
    }
    output += `\n`;
  }

  fs.writeFileSync(outputFile, output, 'utf8');
  console.log(`Successfully generated ${outputFile}`);
}

