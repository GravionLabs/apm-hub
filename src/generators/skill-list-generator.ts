import * as fs from 'fs';
import * as path from 'path';
import { parseFrontmatter } from './template-list-generator';
import {
  collectDomains,
  generateDomainListMarkdown,
  writeOutputFile,
  type DomainEntry,
} from './list-generator';

export function generateSkillList(
  packagesBaseDir = 'packages',
  outputFile = 'docs/skill-list.md'
) {
  const domains = collectDomains(packagesBaseDir);
  const allSkills: DomainEntry[] = [];
  const byDomain: Record<string, DomainEntry[]> = {};

  for (const domain of domains) {
    const skillsSubdir = path.join(packagesBaseDir, domain, '.apm', 'skills');
    if (!fs.existsSync(skillsSubdir)) continue;

    const skillDirs = fs
      .readdirSync(skillsSubdir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();

    const validSkillDirs = skillDirs.filter((name) =>
      fs.existsSync(path.join(skillsSubdir, name, 'SKILL.md'))
    );
    if (validSkillDirs.length === 0) continue;

    byDomain[domain] = [];
    for (const skillName of validSkillDirs) {
      const skillMdPath = path.join(skillsSubdir, skillName, 'SKILL.md');
      const content = fs.readFileSync(skillMdPath, 'utf8');
      const fm = parseFrontmatter(content);
      const name = fm.name || skillName;
      const description = fm.description || '-';
      const relPath = `packages/${domain}/.apm/skills/${skillName}/SKILL.md`;
      const entry: DomainEntry = { domain, name, description, relPath };
      allSkills.push(entry);
      byDomain[domain].push(entry);
    }
  }

  const output = generateDomainListMarkdown(allSkills, byDomain, {
    title: 'Skill List',
    intro: 'This page lists all available skills organized by domain. This file is automatically generated.',
    callout: 'Skills become available as slash commands after installing the corresponding plugin via `gh copilot plugin install`.',
    overviewHeader: 'Skill',
    itemColumnHeader: 'Skill',
  });

  writeOutputFile(outputFile, output);
}

