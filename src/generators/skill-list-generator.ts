import * as fs from 'fs';
import * as path from 'path';
import { parsePluginConfig } from './plugin-list-generator';
import { parseFrontmatter } from './template-list-generator';

function readSkillDescription(pluginsBaseDir: string, pluginDirName: string, skillName: string): string {
  const skillFile = path.join(pluginsBaseDir, pluginDirName, 'skills', skillName, 'SKILL.md');
  if (!fs.existsSync(skillFile)) return '-';
  const content = fs.readFileSync(skillFile, 'utf8');
  const fm = parseFrontmatter(content);
  return fm.description ?? '-';
}

export function generateSkillList(pluginsBaseDir = 'plugins', outputFile = 'docs/skill-list.md') {
  const outputDir = path.dirname(outputFile);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const plugins = [];

  if (fs.existsSync(pluginsBaseDir)) {
    const dirs = fs
      .readdirSync(pluginsBaseDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();

    for (const dirName of dirs) {
      const configPath = path.join(pluginsBaseDir, dirName, 'plugin.config.yml');
      if (fs.existsSync(configPath)) {
        const parsed = parsePluginConfig(configPath);
        plugins.push({ ...parsed, dirName });
      }
    }
  }

  let output = `# Skill List\n\n`;
  output += `This page lists all available skills across all Copilot CLI plugins in this repository. This file is automatically generated.\n\n`;
  output += `> Skills become available as slash commands after installing the corresponding plugin via \`gh copilot plugin install\`.\n\n`;

  // Overview table
  output += `## Overview\n\n`;
  output += `| Skill | Plugin | Description |\n`;
  output += `| :---- | :----- | :---------- |\n`;

  for (const p of plugins) {
    for (const skillName of p.skills) {
      const desc = readSkillDescription(pluginsBaseDir, p.dirName, skillName);
      const skillLink = `[${skillName}](../plugins/${p.dirName}/skills/${skillName})`;
      const pluginLink = `[${p.name}](../plugins/${p.dirName})`;
      output += `| ${skillLink} | ${pluginLink} | ${desc} |\n`;
    }
  }
  output += `\n`;

  // Per-plugin sections
  for (const p of plugins) {
    if (p.skills.length === 0) continue;

    output += `## ${p.name}\n\n`;
    output += `📁 [\`plugins/${p.dirName}\`](../plugins/${p.dirName})\n\n`;

    const desc = p.description.replace(/\n/g, ' ').replace(/\s+/g, ' ').trim();
    if (desc) {
      output += `${desc}\n\n`;
    }

    output += `| Skill | Description |\n`;
    output += `| :---- | :---------- |\n`;

    for (const skillName of p.skills) {
      const skillDesc = readSkillDescription(pluginsBaseDir, p.dirName, skillName);
      const skillLink = `[\`${skillName}\`](../plugins/${p.dirName}/skills/${skillName})`;
      output += `| ${skillLink} | ${skillDesc} |\n`;
    }
    output += `\n`;
  }

  fs.writeFileSync(outputFile, output, 'utf8');
  console.log(`Successfully generated ${outputFile}`);
}
