import * as fs from 'fs';
import * as path from 'path';
import { parse } from 'yaml';
import { parseFrontmatter } from './template-list-generator';
import {
  collectDomains,
  generateDomainListMarkdown,
  writeOutputFile,
  type DomainEntry,
} from './list-generator';

const INTERNAL_OWNER = 'gravionlabs';

/** True when the reference (shorthand, https/ssh URL or scp-style) belongs to the GravionLabs owner. */
function isInternal(ref: string): boolean {
  const rest = ref
    .replace(/^[a-z][a-z0-9+.-]*:\/\/([^/@]*@)?[^/]+\//i, '')
    .replace(/^[^@/]+@[^:/]+:/, '');
  return rest.split('/')[0].toLowerCase() === INTERNAL_OWNER;
}

/** External (non-GravionLabs) `dependencies.apm` entries of a package's apm.yml. */
export function readExternalDependencies(packageDir: string): string[] {
  const manifest = path.join(packageDir, 'apm.yml');
  if (!fs.existsSync(manifest)) return [];
  let doc: unknown;
  try {
    doc = parse(fs.readFileSync(manifest, 'utf8'));
  } catch {
    return [];
  }
  const deps = (doc as { dependencies?: { apm?: unknown } } | null | undefined)?.dependencies;
  const entries = deps?.apm;
  if (!Array.isArray(entries)) return [];
  const result: string[] = [];
  for (const e of entries as unknown[]) {
    let ref: string | undefined;
    if (typeof e === 'string') ref = e;
    else if (e && typeof e === 'object' && typeof (e as { git?: unknown }).git === 'string') {
      const o = e as { git: string; path?: unknown; ref?: unknown };
      ref =
        o.git +
        (typeof o.path === 'string' && o.path ? `/${o.path}` : '') +
        (typeof o.ref === 'string' && o.ref ? `#${o.ref}` : '');
    }
    if (ref && !isInternal(ref)) result.push(ref);
  }
  return result;
}

export function generateSkillList(packagesBaseDir = 'packages', outputFile = 'docs/skill-list.md') {
  const domains = collectDomains(packagesBaseDir);
  const allSkills: DomainEntry[] = [];
  const byDomain: Record<string, DomainEntry[]> = {};

  for (const domain of domains) {
    const skillsSubdir = path.join(packagesBaseDir, domain, '.apm', 'skills');
    if (!fs.existsSync(skillsSubdir)) continue;

    const skillDirs = fs
      .readdirSync(skillsSubdir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();

    const validSkillDirs = skillDirs.filter((name) =>
      fs.existsSync(path.join(skillsSubdir, name, 'SKILL.md'))
    );
    if (validSkillDirs.length === 0) continue;

    byDomain[domain] = [];
    for (const skillName of validSkillDirs) {
      const skillMdPath = path.join(skillsSubdir, skillName, 'SKILL.md');
      const content = fs.readFileSync(skillMdPath, 'utf8');
      const fm = parseFrontmatter(content);
      const name = fm.name || skillName;
      // Gated skills leave the model's skill list; the reader must know to type /<name>.
      const userInvoked = String(fm['disable-model-invocation']).trim() === 'true';
      const description =
        (fm.description || '-') + (userInvoked ? ` *(user-invoked: \`/${name}\`)*` : '');
      const relPath = `packages/${domain}/.apm/skills/${skillName}/SKILL.md`;
      const entry: DomainEntry = { domain, name, description, relPath };
      allSkills.push(entry);
      byDomain[domain].push(entry);
    }
  }

  let output = generateDomainListMarkdown(allSkills, byDomain, {
    title: 'Skill List',
    intro:
      'This page lists all available skills organized by domain. This file is automatically generated.',
    callout:
      'Skills become available as slash commands after installing the corresponding plugin via `gh copilot plugin install`.',
    overviewHeader: 'Skill',
    itemColumnHeader: 'Skill',
  });

  for (const domain of Object.keys(byDomain)) {
    const deps = readExternalDependencies(path.join(packagesBaseDir, domain));
    if (deps.length === 0) continue;
    const label = domain.charAt(0).toUpperCase() + domain.slice(1);
    const heading = `\n## ${label}\n\n`;
    output = output.replace(
      heading,
      () => `${heading}External dependencies: ${deps.map((d) => `\`${d}\``).join(', ')}\n\n`
    );
  }

  writeOutputFile(outputFile, output);
}
