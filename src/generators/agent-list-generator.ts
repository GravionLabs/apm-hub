import * as fs from 'fs';
import * as path from 'path';
import { parseFrontmatter } from './template-list-generator';
import {
  collectDomains,
  generateDomainListMarkdown,
  writeOutputFile,
  type DomainEntry,
} from './list-generator';

export function generateAgentList(
  packagesBaseDir = 'packages',
  outputFile = 'docs/agent-list.md'
) {
  const allAgents: DomainEntry[] = [];
  const byDomain: Record<string, DomainEntry[]> = {};

  for (const domain of collectDomains(packagesBaseDir)) {
    const agentsDir = path.join(packagesBaseDir, domain, '.apm', 'agents');
    if (!fs.existsSync(agentsDir)) continue;

    const files = fs
      .readdirSync(agentsDir)
      .filter((f) => f.endsWith('.agent.md'))
      .sort();
    if (files.length === 0) continue;

    byDomain[domain] = [];
    for (const file of files) {
      const content = fs.readFileSync(path.join(agentsDir, file), 'utf8');
      const fm = parseFrontmatter(content);
      const stem = file.slice(0, -'.agent.md'.length);
      const name = fm.name || stem;
      // Subagents are started by the orchestrator or the model, not from the agent picker.
      const subagent = String(fm['user-invocable']).trim() === 'false';
      const description = (fm.description || '-') + (subagent ? ' *(subagent)*' : '');
      const relPath = `packages/${domain}/.apm/agents/${file}`;
      const entry: DomainEntry = { domain, name, description, relPath };
      allAgents.push(entry);
      byDomain[domain].push(entry);
    }
  }

  const output = generateDomainListMarkdown(allAgents, byDomain, {
    title: 'Agent List',
    intro: 'This page lists all agents organized by package. This file is automatically generated.',
    callout:
      'Agents deploy to `.claude/agents`, `.github/agents` and `.opencode/agents` with `apm install`; run `apmw sanitize -p <platform>` afterwards so each client gets its own frontmatter. Start the orchestrator with `claude --agent orchestrator`, `copilot --agent orchestrator` or `opencode --agent orchestrator`.',
    overviewHeader: 'Agent',
    itemColumnHeader: 'Agent',
  });

  writeOutputFile(outputFile, output);
}
