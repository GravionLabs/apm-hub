import * as fs from 'fs';
import * as path from 'path';
import { getTitle, parseFrontmatter } from './template-list-generator';

export function generateAgentList(
  templatesBaseDir = 'templates',
  outputFile = 'docs/agent-list.md'
) {
  const outputDir = path.dirname(outputFile);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Collect domain directories
  const domains: string[] = [];
  if (fs.existsSync(templatesBaseDir)) {
    fs.readdirSync(templatesBaseDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort()
      .forEach((d) => domains.push(d));
  }

  interface AgentEntry {
    domain: string;
    name: string;
    description: string;
    filename: string;
    relPath: string;
  }

  const allAgents: AgentEntry[] = [];
  const byDomain: Record<string, AgentEntry[]> = {};

  for (const domain of domains) {
    // Agents are in templates/<domain>/agents/*.agent.md
    const agentsDir = path.join(templatesBaseDir, domain, 'agents');
    if (!fs.existsSync(agentsDir)) continue;

    const files = fs
      .readdirSync(agentsDir, { withFileTypes: true })
      .filter((f) => f.isFile() && f.name.endsWith('.agent.md'))
      .map((f) => f.name)
      .sort();

    if (files.length === 0) continue;

    byDomain[domain] = [];
    for (const filename of files) {
      const content = fs.readFileSync(path.join(agentsDir, filename), 'utf8');
      const fm = parseFrontmatter(content);
      const name = fm.name || getTitle(content, filename);
      const description = fm.description || '-';
      const relPath = `${domain}/agents/${filename}`;
      const entry: AgentEntry = { domain, name, description, filename, relPath };
      allAgents.push(entry);
      byDomain[domain].push(entry);
    }
  }

  let output = `# Agent List\n\n`;
  output += `This page lists all available agents organized by domain. This file is automatically generated.\n\n`;
  output += `> Agents become available in GitHub Copilot after installing the corresponding plugin via \`gh copilot plugin install\`.\n\n`;

  // Overview table
  output += `## Overview\n\n`;
  output += `| Agent | Domain | Description |\n`;
  output += `| :---- | :----- | :---------- |\n`;

  for (const a of allAgents) {
    const agentLink = `[${a.name}](../templates/${a.relPath})`;
    const domainLabel = a.domain.charAt(0).toUpperCase() + a.domain.slice(1);
    const domainLink = `[${domainLabel}](#${a.domain})`;
    output += `| ${agentLink} | ${domainLink} | ${a.description} |\n`;
  }
  output += `\n`;

  // Per-domain sections
  for (const [domain, agents] of Object.entries(byDomain)) {
    const label = domain.charAt(0).toUpperCase() + domain.slice(1);
    output += `## ${label}\n\n`;
    output += `| Agent | Description |\n`;
    output += `| :---- | :---------- |\n`;
    for (const a of agents) {
      const agentLink = `[\`${a.name}\`](../templates/${a.relPath})`;
      output += `| ${agentLink} | ${a.description} |\n`;
    }
    output += `\n`;
  }

  fs.writeFileSync(outputFile, output, 'utf8');
  console.log(`Successfully generated ${outputFile}`);
}
