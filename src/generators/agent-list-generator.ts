import * as fs from 'fs';
import * as path from 'path';
import { getTitle, parseFrontmatter } from './template-list-generator';
import {
  collectDomains,
  generateDomainListMarkdown,
  writeOutputFile,
  type DomainEntry,
} from './list-generator';

export function generateAgentList(
  packagesBaseDir = 'packages',
  outputFile = 'docs/agent-list.md'
) {
  const domains = collectDomains(packagesBaseDir);
  const allAgents: DomainEntry[] = [];
  const byDomain: Record<string, DomainEntry[]> = {};

  for (const domain of domains) {
    const agentsDir = path.join(packagesBaseDir, domain, '.apm', 'agents');
    if (!fs.existsSync(agentsDir)) continue;

    const files = fs
      .readdirSync(agentsDir, { withFileTypes: true })
      .filter((f) => f.isFile() && f.name.endsWith('.agent.md'))
      .map((f) => f.name)
      .sort();

    if (files.length === 0) continue;

    byDomain[domain] = [];
    for (const filename of files) {
      const content = fs.readFileSync(path.join(agentsDir, filename), 'utf8');
      const fm = parseFrontmatter(content);
      const name = fm.name || getTitle(content, filename);
      const description = fm.description || '-';
      const relPath = `packages/${domain}/.apm/agents/${filename}`;
      const entry: DomainEntry = { domain, name, description, relPath };
      allAgents.push(entry);
      byDomain[domain].push(entry);
    }
  }

  const output = generateDomainListMarkdown(allAgents, byDomain, {
    title: 'Agent List',
    intro: 'This page lists all available agents organized by domain. This file is automatically generated.',
    callout: 'Agents become available in GitHub Copilot after installing the corresponding plugin via `gh copilot plugin install`.',
    overviewHeader: 'Agent',
    itemColumnHeader: 'Agent',
  });

  writeOutputFile(outputFile, output);
}
