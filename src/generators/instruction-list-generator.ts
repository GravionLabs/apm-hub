import * as fs from 'fs';
import * as path from 'path';
import { parseFrontmatter } from './template-list-generator';
import {
  collectDomains,
  generateDomainListMarkdown,
  writeOutputFile,
  type DomainEntry,
} from './list-generator';

export function generateInstructionList(
  packagesBaseDir = 'packages',
  outputFile = 'docs/instruction-list.md'
) {
  const domains = collectDomains(packagesBaseDir);
  const allInstructions: DomainEntry[] = [];
  const byDomain: Record<string, DomainEntry[]> = {};

  for (const domain of domains) {
    const instructionsDir = path.join(packagesBaseDir, domain, '.apm', 'instructions');
    if (!fs.existsSync(instructionsDir)) continue;

    const files = fs
      .readdirSync(instructionsDir, { withFileTypes: true })
      .filter((f) => f.isFile() && f.name.endsWith('.instructions.md'))
      .map((f) => f.name)
      .sort();

    if (files.length === 0) continue;

    byDomain[domain] = [];
    for (const filename of files) {
      const content = fs.readFileSync(path.join(instructionsDir, filename), 'utf8');
      const fm = parseFrontmatter(content);
      const name = fm.name || filename.replace('.instructions.md', '');
      const description = fm.description || '-';
      const relPath = `packages/${domain}/.apm/instructions/${filename}`;
      const entry: DomainEntry = { domain, name, description, relPath };
      allInstructions.push(entry);
      byDomain[domain].push(entry);
    }
  }

  const output = generateDomainListMarkdown(allInstructions, byDomain, {
    title: 'Instruction List',
    intro:
      'This page lists all available instructions organized by domain. This file is automatically generated.',
    callout:
      'Instructions are automatically loaded as context by GitHub Copilot after installing the corresponding plugin via `gh copilot plugin install`.',
    overviewHeader: 'Instruction',
    itemColumnHeader: 'Instruction',
  });

  writeOutputFile(outputFile, output);
}
