import * as fs from 'fs';
import * as path from 'path';
import { parseFrontmatter } from './template-list-generator';

export function generateInstructionList(
  templatesBaseDir = 'templates',
  outputFile = 'docs/instruction-list.md'
) {
  const outputDir = path.dirname(outputFile);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Collect domain directories
  const domains: string[] = [];
  if (fs.existsSync(templatesBaseDir)) {
    fs.readdirSync(templatesBaseDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort()
      .forEach((d) => domains.push(d));
  }

  interface InstructionEntry {
    domain: string;
    name: string;
    description: string;
    filename: string;
  }

  const allInstructions: InstructionEntry[] = [];
  const byDomain: Record<string, InstructionEntry[]> = {};

  for (const domain of domains) {
    const domainDir = path.join(templatesBaseDir, domain);
    const files = fs
      .readdirSync(domainDir, { withFileTypes: true })
      .filter((f) => f.isFile() && f.name.endsWith('.instructions.md'))
      .map((f) => f.name)
      .sort();

    if (files.length === 0) continue;

    byDomain[domain] = [];
    for (const filename of files) {
      const content = fs.readFileSync(path.join(domainDir, filename), 'utf8');
      const fm = parseFrontmatter(content);
      const name = fm.name || filename.replace('.instructions.md', '');
      const description = fm.description || '-';
      const entry: InstructionEntry = { domain, name, description, filename };
      allInstructions.push(entry);
      byDomain[domain].push(entry);
    }
  }

  let output = `# Instruction List\n\n`;
  output += `This page lists all available instructions organized by domain. This file is automatically generated.\n\n`;
  output += `> Instructions are automatically loaded as context by GitHub Copilot after installing the corresponding plugin via \`gh copilot plugin install\`.\n\n`;

  // Overview table
  output += `## Overview\n\n`;
  output += `| Instruction | Domain | Description |\n`;
  output += `| :---------- | :----- | :---------- |\n`;

  for (const i of allInstructions) {
    const instrLink = `[${i.name}](../templates/${i.domain}/${i.filename})`;
    const domainLabel = i.domain.charAt(0).toUpperCase() + i.domain.slice(1);
    const domainLink = `[${domainLabel}](#${i.domain})`;
    output += `| ${instrLink} | ${domainLink} | ${i.description} |\n`;
  }
  output += `\n`;

  // Per-domain sections
  for (const [domain, instructions] of Object.entries(byDomain)) {
    const label = domain.charAt(0).toUpperCase() + domain.slice(1);
    output += `## ${label}\n\n`;
    output += `| Instruction | Description |\n`;
    output += `| :---------- | :---------- |\n`;
    for (const i of instructions) {
      const instrLink = `[\`${i.name}\`](../templates/${i.domain}/${i.filename})`;
      output += `| ${instrLink} | ${i.description} |\n`;
    }
    output += `\n`;
  }

  fs.writeFileSync(outputFile, output, 'utf8');
  console.log(`Successfully generated ${outputFile}`);
}
