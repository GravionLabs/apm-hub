import * as fs from 'fs';
import * as path from 'path';
import { getTitle, parseFrontmatter } from '../utils/markdown-parser';
import { collectDomains, writeOutputFile } from './list-generator';

export { getTitle, parseFrontmatter };

/** Type subdirectory name → display type label */
const SUBDIR_TYPE_LABELS: Record<string, string> = {
  agents: 'Agent',
  skills: 'Skill',
  instructions: 'Instructions',
};

/** Flat file extension → display type label (for agents, instructions subdirs) */
const EXT_TYPE_LABELS: Record<string, string> = {
  '.agent.md': 'Agent',
  '.instructions.md': 'Instructions',
};

function getExtType(filename: string): string | null {
  for (const ext of Object.keys(EXT_TYPE_LABELS)) {
    if (filename.endsWith(ext)) return EXT_TYPE_LABELS[ext];
  }
  return null;
}

interface TemplateEntry {
  /** Relative path from templatesBaseDir for use in doc links */
  relPath: string;
  /** Link text shown in the table */
  linkText: string;
  type: string;
  name: string;
  description: string;
}

/**
 * Collect all package entries for a single domain directory (.apm/ subdirectory).
 * Handles both:
 *  - subdirectory layout: `<domain>/.apm/<type>/<name>.{agent,instructions}.md`
 *  - skill directory layout: `<domain>/.apm/skills/<name>/SKILL.md`  (agentskills.io spec)
 */
function collectDomainEntries(apmDir: string, domain: string): TemplateEntry[] {
  if (!fs.existsSync(apmDir)) return [];
  const entries: TemplateEntry[] = [];

  const subdirs = fs.readdirSync(apmDir, { withFileTypes: true }).filter((d) => d.isDirectory());

  for (const subdir of subdirs.sort((a, b) => a.name.localeCompare(b.name))) {
    const typeLabel = SUBDIR_TYPE_LABELS[subdir.name];
    if (!typeLabel) continue;

    const subdirPath = path.join(apmDir, subdir.name);

    if (subdir.name === 'skills') {
      // Skills use the agentskills.io directory layout: <skill-name>/SKILL.md
      const skillDirs = fs
        .readdirSync(subdirPath, { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .sort((a, b) => a.name.localeCompare(b.name));

      for (const skillDir of skillDirs) {
        const skillMdPath = path.join(subdirPath, skillDir.name, 'SKILL.md');
        if (!fs.existsSync(skillMdPath)) continue;

        const relPath = `packages/${domain}/.apm/skills/${skillDir.name}/SKILL.md`;
        const content = fs.readFileSync(skillMdPath, 'utf8');
        const fm = parseFrontmatter(content);
        const name = fm.name || skillDir.name;
        const description = fm.description || '-';
        entries.push({ relPath, linkText: name, type: typeLabel, name, description });
      }
    } else {
      // agents/, prompts/, instructions/ — flat files with extension-based type
      const files = fs
        .readdirSync(subdirPath, { withFileTypes: true })
        .filter((f) => f.isFile())
        .sort((a, b) => a.name.localeCompare(b.name));

      for (const file of files) {
        const extType = getExtType(file.name);
        if (!extType) continue;

        const filePath = path.join(subdirPath, file.name);
        const content = fs.readFileSync(filePath, 'utf8');
        const fm = parseFrontmatter(content);
        const name = fm.name || getTitle(content, file.name);
        const description = fm.description || '-';
        const relPath = `packages/${domain}/.apm/${subdir.name}/${file.name}`;
        entries.push({ relPath, linkText: file.name, type: extType, name, description });
      }
    }
  }

  return entries;
}

/** Fixed display order for type subsections */
const TYPE_ORDER: string[] = ['Agent', 'Instructions', 'Skill'];

/** Heading labels for each type */
const TYPE_HEADINGS: Record<string, string> = {
  Agent: 'Agents',
  Instructions: 'Instructions',
  Skill: 'Skills',
};

export function generateTemplateList(
  packagesBaseDir = 'packages',
  outputFile = 'docs/template-list.md',
) {
  const domains = collectDomains(packagesBaseDir);

  let output = `# Package List\n\n`;
  output += `This page lists all available packages (Agents, Skills, Instructions) organized by domain. This file is automatically generated.\n\n`;

  // Table of Contents (only include domains that have entries)
  const domainEntries = new Map<string, TemplateEntry[]>();
  for (const domain of domains) {
    const apmDir = path.join(packagesBaseDir, domain, '.apm');
    const entries = collectDomainEntries(apmDir, domain);
    if (entries.length > 0) domainEntries.set(domain, entries);
  }

  output += `## Table of Contents\n\n`;
  for (const domain of domainEntries.keys()) {
    const anchor = domain.toLowerCase().replace(/\s+/g, '-');
    const label = domain.charAt(0).toUpperCase() + domain.slice(1);
    output += `- [${label}](#${anchor})\n`;
  }
  output += `\n`;

  // Per-domain sections, each type in its own subsection
  for (const [domain, entries] of domainEntries) {
    const label = domain.charAt(0).toUpperCase() + domain.slice(1);
    output += `## ${label}\n\n`;

    // Group by type
    const byType = new Map<string, TemplateEntry[]>();
    for (const e of entries) {
      if (!byType.has(e.type)) byType.set(e.type, []);
      byType.get(e.type)!.push(e);
    }

    for (const type of TYPE_ORDER) {
      const typeEntries = byType.get(type);
      if (!typeEntries || typeEntries.length === 0) continue;

      output += `### ${TYPE_HEADINGS[type]}\n\n`;
      output += `| Name | Description | File |\n`;
      output += `| :--- | :---------- | :--- |\n`;

      for (const e of typeEntries) {
        const fileLink = `[${e.linkText}](../${e.relPath})`;
        output += `| ${e.name} | ${e.description} | ${fileLink} |\n`;
      }
      output += `\n`;
    }
  }

  writeOutputFile(outputFile, output);
}
