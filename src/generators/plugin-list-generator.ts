import * as fs from 'fs';
import * as path from 'path';
import { parse } from 'yaml';

interface PluginSkillEntry {
  name: string;
  source?: string;
}

interface PluginAgentEntry {
  source: string;
}

interface PluginInstructionEntry {
  source: string;
}

interface PluginMetadata {
  name: string;
  description?: string;
  version?: string;
  skills?: (string | PluginSkillEntry)[];
  agents?: (string | PluginAgentEntry)[];
  instructions?: (string | PluginInstructionEntry)[];
  keywords?: string[];
}

export interface ParsedPlugin {
  dirName: string;
  name: string;
  description: string;
  skillCount: number;
  agentCount: number;
  instructionCount: number;
  skills: string[];
  agents: string[];
  instructions: string[];
  keywords: string[];
}

export function parsePluginConfig(configPath: string): ParsedPlugin {
  const dirName = path.basename(path.dirname(configPath));
  const raw = fs.readFileSync(configPath, 'utf8');
  const config = parse(raw) as PluginMetadata;

  const skills = (config.skills ?? []).map((s) =>
    typeof s === 'string' ? s : s.name,
  );
  const agents = (config.agents ?? []).map((a) =>
    typeof a === 'string' ? a : a.source,
  );
  const instructions = (config.instructions ?? []).map((i) =>
    typeof i === 'string' ? i : i.source,
  );

  return {
    dirName,
    name: config.name ?? dirName,
    description: config.description ?? '',
    skillCount: skills.length,
    agentCount: agents.length,
    instructionCount: instructions.length,
    skills,
    agents,
    instructions,
    keywords: config.keywords ?? [],
  };
}

export function generatePluginList(pluginsBaseDir = 'plugins', outputFile = 'docs/plugin-list.md') {
  const outputDir = path.dirname(outputFile);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const plugins: ParsedPlugin[] = [];

  if (fs.existsSync(pluginsBaseDir)) {
    const dirs = fs
      .readdirSync(pluginsBaseDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();

    for (const dirName of dirs) {
      const configPath = path.join(pluginsBaseDir, dirName, 'plugin.config.yml');
      if (fs.existsSync(configPath)) {
        plugins.push(parsePluginConfig(configPath));
      }
    }
  }

  let output = `# Plugin List\n\n`;
  output += `This page lists all available Copilot CLI plugins in this repository. This file is automatically generated.\n\n`;
  output += `> Each plugin can be installed by pointing the Copilot CLI at its \`.github/plugin/plugin.json\` manifest.\n\n`;

  output += `## Overview\n\n`;
  output += `| Plugin | Description | Skills | Agents | Instructions |\n`;
  output += `| :--- | :--- | :---: | :---: | :---: |\n`;

  for (const p of plugins) {
    const link = `[${p.name}](#${p.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')})`;
    const desc = p.description.replace(/\n/g, ' ').replace(/\s+/g, ' ').trim();
    output += `| ${link} | ${desc} | ${p.skillCount} | ${p.agentCount} | ${p.instructionCount} |\n`;
  }
  output += `\n`;

  for (const p of plugins) {
    const anchor = p.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    output += `## ${p.name}\n\n`;

    const relDir = `../plugins/${p.dirName}`;
    output += `📁 [\`plugins/${p.dirName}\`](${relDir})\n\n`;

    if (p.description) {
      const desc = p.description.replace(/\n/g, ' ').replace(/\s+/g, ' ').trim();
      output += `${desc}\n\n`;
    }

    if (p.keywords.length > 0) {
      output += `**Keywords:** ${p.keywords.map((k) => `\`${k}\``).join(', ')}\n\n`;
    }

    if (p.skills.length > 0) {
      output += `**Skills (${p.skillCount}):**\n`;
      for (const s of p.skills) {
        const skillDir = `${relDir}/skills/${s}`;
        output += `- [\`${s}\`](${skillDir})\n`;
      }
      output += `\n`;
    }

    if (p.agents.length > 0) {
      output += `**Agents (${p.agentCount}):**\n`;
      for (const a of p.agents) {
        const filename = `${a}.agent.md`;
        output += `- [\`${filename}\`](${relDir}/agents/${filename})\n`;
      }
      output += `\n`;
    }

    if (p.instructions.length > 0) {
      output += `**Instructions (${p.instructionCount}):**\n`;
      for (const i of p.instructions) {
        const filename = `${i}.instructions.md`;
        output += `- [\`${filename}\`](${relDir}/instructions/${filename})\n`;
      }
      output += `\n`;
    }

    // anchor reference for TOC links
    void anchor;
  }

  fs.writeFileSync(outputFile, output, 'utf8');
  console.log(`Successfully generated ${outputFile}`);
}
